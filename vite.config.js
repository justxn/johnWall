import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig } from 'vite';

// Everything in public/ (manifest, icons), as paths relative to the site root.
function publicFiles(dir = 'public') {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? publicFiles(path) : [relative('public', path).split('\\').join('/')];
  });
}

const swSource = (version, files) => `// Generated by vite.config.js at build time.
const CACHE = 'hoops-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hoops-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Pages come from the network when possible, so a new version shows up right
// away; the cached copy is the offline fallback. Built files have unique names,
// so those come from the cache first. Firestore traffic isn't touched: the
// Firebase SDK keeps its own offline copy of the data.
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./')));
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;

// Writes sw.js with the exact files of this build, so the installed app opens
// with no signal once it has been opened online.
function serviceWorker() {
  return {
    name: 'hoops-service-worker',
    apply: 'build',
    enforce: 'post',
    generateBundle(_, bundle) {
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const extra = publicFiles();
      const hash = createHash('sha1');
      for (const f of built) hash.update(f).update(f === 'index.html' ? String(bundle[f].source) : '');
      for (const f of extra) hash.update(f).update(readFileSync(join('public', f)));
      const files = ['./', ...[...built, ...extra].map((f) => `./${f}`)];
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(hash.digest('hex').slice(0, 12), files) });
    },
  };
}

// Relative base so the build works under a GitHub Pages sub-path.
export default defineConfig({
  base: './',
  plugins: [serviceWorker()],
  build: {
    chunkSizeWarningLimit: 700, // the Firebase chunk is ~630 kB (190 kB gzipped) and that's expected
    rolldownOptions: {
      output: {
        // Firebase changes far less often than the app, so keep it in its own
        // file that phones can keep cached between updates.
        codeSplitting: { groups: [{ name: 'firebase', test: /node_modules[\\/](@firebase|firebase)[\\/]/ }] },
      },
    },
  },
  test: {
    include: ['tests/**/*.test.js'],
    exclude: ['tests/rules/**', '**/node_modules/**'],
  },
});
